// ---- the token exchange ----

/// A request the tester made, and what came back, exactly as it went over the
/// wire. This is the whole point of using a real client: what is displayed is what
/// a client would have sent and received.
#[derive(Debug, Clone, Default)]
pub struct HttpCall {
    pub url: String,
    pub headers: Vec<(String, String)>,
    pub body: String,
    pub status: Option<u16>,
    pub response: Option<String>,
    /// Set when the request never got an answer: TLS, DNS, a refused connection.
    pub transport_error: Option<String>,
}

impl HttpCall {
    /// The parsed response body, when it was JSON.
    pub fn json(&self) -> Option<Value> {
        serde_json::from_str(self.response.as_deref()?).ok()
    }
}

/// The method is always POST, but it is shown on the page, so it is named here.
pub const TOKEN_METHOD: &str = "POST";
const FORM_CONTENT_TYPE: &str = "application/x-www-form-urlencoded";

/// How long the tester waits for its own token endpoint. Invented: ten seconds.
/// Long enough for a cold connection, short enough that a wedged endpoint shows as
/// a timeout on the page instead of hanging the console.
const EXCHANGE_TIMEOUT_SECS: u64 = 10;

/// Redeem the code at our own token endpoint, over HTTP.
///
/// Never panics and never returns `Err`: a failed exchange is a result the page has
/// to show, not an error page. The reply is returned verbatim.
pub async fn exchange(url: &PublicUrl, pending: &Pending, code: &str, platform: RedirectPlatform) -> HttpCall {
    let endpoint = url.tenant_url(&pending.tenant_id, "oauth2/v2.0/token");
    // In its own scope: the serializer is not `Send`, and this function holds its
    // result across an await.
    let body = {
        let mut form = url::form_urlencoded::Serializer::new(String::new());
        form.append_pair("grant_type", crate::routes::GrantType::AuthorizationCode.as_str());
        form.append_pair("client_id", &pending.client_app_id);
        form.append_pair("code", code);
        form.append_pair("redirect_uri", &pending.redirect_uri);
        form.append_pair("scope", &pending.scope);
        if let Some(verifier) = &pending.code_verifier {
            form.append_pair("code_verifier", verifier);
        }
        form.finish()
    };

    let mut headers = vec![(reqwest::header::CONTENT_TYPE.to_string(), FORM_CONTENT_TYPE.to_string())];
    // An spa client may only redeem cross-origin, so the request has to look like
    // one. A web or public client must *not* send Origin: the token endpoint
    // refuses cross-origin redemption for anything but an spa.
    if platform == RedirectPlatform::Spa
        && let Ok(parsed) = url::Url::parse(&pending.redirect_uri)
    {
        headers.push((
            reqwest::header::ORIGIN.to_string(),
            parsed.origin().ascii_serialization(),
        ));
    }

    let mut call = HttpCall {
        url: endpoint.clone(),
        headers: headers.clone(),
        body: body.clone(),
        ..Default::default()
    };

    // No proxy: this is a request to ourselves, and an ambient proxy variable must
    // not quietly put a middlebox between the console and the endpoint it is
    // testing.
    let client = match reqwest::Client::builder()
        .no_proxy()
        .timeout(std::time::Duration::from_secs(EXCHANGE_TIMEOUT_SECS))
        .build()
    {
        Ok(c) => c,
        Err(e) => {
            call.transport_error = Some(e.to_string());
            return call;
        }
    };
    let mut request = client.post(&endpoint).body(body);
    for (name, value) in &headers {
        request = request.header(name.as_str(), value.as_str());
    }
    match request.send().await {
        Ok(resp) => {
            call.status = Some(resp.status().as_u16());
            call.response = Some(resp.text().await.unwrap_or_else(|e| format!("<unreadable body: {e}>")));
        }
        Err(e) => call.transport_error = Some(e.to_string()),
    }
    call
}

// ---- reading what came back ----

/// Claim names the result page checks. Spelled once each.
pub const CLAIM_NONCE: &str = "nonce";
pub const CLAIM_C_HASH: &str = "c_hash";
pub const CLAIM_AT_HASH: &str = "at_hash";
pub const CLAIM_ISS: &str = "iss";
pub const CLAIM_AUD: &str = "aud";
pub const CLAIM_EXP: &str = "exp";

/// A JWT, taken apart for display. `signature` is the outcome of verifying it
/// against this deployment's published signing keys.
pub struct DecodedToken {
    pub header: Value,
    pub claims: Value,
    pub signature: Result<(), String>,
}

/// Split a compact JWS and decode its two JSON parts. The signature is not checked
/// here: [`crate::keys::KeyStore::verify`] does that, and a token that fails it
/// still has to be displayed.
pub fn decode_parts(token: &str) -> anyhow::Result<(Value, Value)> {
    use base64::Engine;
    let mut parts = token.split('.');
    let header = parts.next().unwrap_or_default();
    let claims = parts.next().unwrap_or_default();
    anyhow::ensure!(parts.next().is_some(), "not a compact JWS: expected three parts");
    let decode = |part: &str| -> anyhow::Result<Value> {
        let bytes = base64::engine::general_purpose::URL_SAFE_NO_PAD
            .decode(part)
            .context("a JWT part is not base64url")?;
        serde_json::from_slice(&bytes).context("a JWT part is not JSON")
    };
    Ok((decode(header)?, decode(claims)?))
}

/// One thing checked on a token that came back.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Check {
    Signature,
    Issuer,
    Audience,
    Expiry,
    Nonce,
    CodeHash,
    AccessTokenHash,
}

impl Check {
    pub const ALL: &'static [Check] = &[
        Self::Signature,
        Self::Issuer,
        Self::Audience,
        Self::Expiry,
        Self::Nonce,
        Self::CodeHash,
        Self::AccessTokenHash,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Signature => "signature",
            Self::Issuer => CLAIM_ISS,
            Self::Audience => CLAIM_AUD,
            Self::Expiry => CLAIM_EXP,
            Self::Nonce => CLAIM_NONCE,
            Self::CodeHash => CLAIM_C_HASH,
            Self::AccessTokenHash => CLAIM_AT_HASH,
        }
    }

    pub fn title(self) -> &'static str {
        match self {
            Self::Signature => "Signature",
            Self::Issuer => "iss",
            Self::Audience => "aud",
            Self::Expiry => "exp",
            Self::Nonce => "nonce",
            Self::CodeHash => "c_hash",
            Self::AccessTokenHash => "at_hash",
        }
    }
}

/// The outcome of one check, with what was seen.
#[derive(Debug, Clone)]
pub struct Observation {
    pub check: Check,
    pub verdict: Verdict,
    pub detail: String,
}

impl Observation {
    fn new(check: Check, verdict: Verdict, detail: impl Into<String>) -> Self {
        Self {
            check,
            verdict,
            detail: detail.into(),
        }
    }
}

/// What an ID token is checked against.
pub struct Expected<'a> {
    pub issuer: &'a str,
    pub audience: &'a str,
    pub nonce: Option<&'a str>,
    /// The code delivered in the same response, for `c_hash`.
    pub code: Option<&'a str>,
    /// The access token delivered in the same response, for `at_hash`.
    pub access_token: Option<&'a str>,
}

/// Check an ID token's binding to this request. Pure, so it is testable without a
/// server: every input is already in hand by the time it is called.
pub fn check_id_token(token: &DecodedToken, expected: &Expected<'_>) -> Vec<Observation> {
    let claims = &token.claims;
    let mut out = vec![signature_observation(token)];
    out.push(string_claim(claims, Check::Issuer, CLAIM_ISS, expected.issuer));
    out.push(audience_matches(claims, expected.audience));
    out.push(expiry(claims));
    out.push(
        match (expected.nonce, claims.get(CLAIM_NONCE).and_then(Value::as_str)) {
            (Some(want), Some(got)) if got == want => {
                Observation::new(Check::Nonce, Verdict::Pass, "Matches the nonce this request sent.")
            }
            (Some(_), Some(_)) => Observation::new(
                Check::Nonce,
                Verdict::Fail,
                "Does not match the nonce this request sent: this token belongs to a different request.",
            ),
            (Some(_), None) => Observation::new(
                Check::Nonce,
                Verdict::Fail,
                "Absent, although the request sent a nonce. An ID token must echo it.",
            ),
            (None, _) => Observation::new(Check::Nonce, Verdict::Note, "The request sent no nonce."),
        },
    );
    out.push(half_hash_check(
        Check::CodeHash,
        claims.get(CLAIM_C_HASH).and_then(Value::as_str),
        expected.code,
        "code",
    ));
    out.push(half_hash_check(
        Check::AccessTokenHash,
        claims.get(CLAIM_AT_HASH).and_then(Value::as_str),
        expected.access_token,
        "access token",
    ));
    out
}

/// Check an access token, which carries no `nonce` and no hash claims. Our access
/// tokens are JWTs; another server's might be opaque, which is why the caller only
/// gets here once it decoded one.
pub fn check_access_token(token: &DecodedToken, issuer: &str, audience: Option<&str>) -> Vec<Observation> {
    let claims = &token.claims;
    let mut out = vec![signature_observation(token)];
    out.push(string_claim(claims, Check::Issuer, CLAIM_ISS, issuer));
    out.push(match audience {
        Some(want) => audience_matches(claims, want),
        None => match claims.get(CLAIM_AUD) {
            Some(aud) => Observation::new(
                Check::Audience,
                Verdict::Note,
                format!("{aud}. The scope did not name a resource, so there is nothing to compare it to."),
            ),
            None => Observation::new(Check::Audience, Verdict::Fail, "Absent."),
        },
    });
    out.push(expiry(claims));
    out
}

fn signature_observation(token: &DecodedToken) -> Observation {
    match &token.signature {
        Ok(()) => Observation::new(
            Check::Signature,
            Verdict::Pass,
            "Verified against this deployment's published signing keys.",
        ),
        Err(e) => Observation::new(
            Check::Signature,
            Verdict::Fail,
            format!("Does not verify against this deployment's published signing keys: {e}"),
        ),
    }
}

fn string_claim(claims: &Value, check: Check, name: &str, expected: &str) -> Observation {
    match claims.get(name).and_then(Value::as_str) {
        Some(got) if got == expected => Observation::new(check, Verdict::Pass, got.to_string()),
        Some(got) => Observation::new(check, Verdict::Fail, format!("{got}, expected {expected}")),
        None => Observation::new(check, Verdict::Fail, format!("Absent, expected {expected}")),
    }
}

/// `aud` may be a string or an array of strings (RFC 7519); ours is a string.
fn audience_matches(claims: &Value, expected: &str) -> Observation {
    let got = claims.get(CLAIM_AUD);
    let matches = match got {
        Some(Value::String(s)) => s == expected,
        Some(Value::Array(items)) => items.iter().any(|i| i.as_str() == Some(expected)),
        _ => false,
    };
    match (got, matches) {
        (Some(aud), true) => Observation::new(Check::Audience, Verdict::Pass, aud.to_string()),
        (Some(aud), false) => Observation::new(Check::Audience, Verdict::Fail, format!("{aud}, expected {expected}")),
        (None, _) => Observation::new(Check::Audience, Verdict::Fail, format!("Absent, expected {expected}")),
    }
}

fn expiry(claims: &Value) -> Observation {
    match claims.get(CLAIM_EXP).and_then(Value::as_i64) {
        Some(exp) => {
            let left = exp - now();
            if left > 0 {
                Observation::new(
                    Check::Expiry,
                    Verdict::Pass,
                    format!("{} ({left}s from now)", crate::admin::view::ts(exp)),
                )
            } else {
                Observation::new(
                    Check::Expiry,
                    Verdict::Fail,
                    format!("{}, which is {}s in the past", crate::admin::view::ts(exp), -left),
                )
            }
        }
        None => Observation::new(Check::Expiry, Verdict::Fail, "Absent."),
    }
}

/// `c_hash` and `at_hash` are the same construction over different values.
fn half_hash_check(check: Check, claimed: Option<&str>, value: Option<&str>, what: &str) -> Observation {
    match (claimed, value) {
        (Some(claimed), Some(value)) => {
            let want = half_hash(value);
            if claimed == want {
                Observation::new(
                    check,
                    Verdict::Pass,
                    format!("{claimed}, which is the left half of SHA-256 over the {what} in this response."),
                )
            } else {
                Observation::new(
                    check,
                    Verdict::Fail,
                    format!("{claimed}, but the {what} in this response hashes to {want}."),
                )
            }
        }
        (Some(claimed), None) => Observation::new(
            check,
            Verdict::Fail,
            format!(
                "{claimed} is present although no {what} came back in the same response, so there is nothing it can bind."
            ),
        ),
        (None, Some(_)) => Observation::new(
            check,
            Verdict::Note,
            format!(
                "Absent. Required only when the {what} travels in the same response as the ID token, \
                 which is the hybrid flow."
            ),
        ),
        (None, None) => Observation::new(check, Verdict::Note, format!("Absent, and no {what} to bind.")),
    }
}

/// How a flow test ended, for the one audit row that records it. Never any of the
/// material: this is the whole of what the log learns.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Outcome {
    /// The callback could not be matched to a pending flow test.
    StateUnknown,
    /// The server answered the authorize request with an OAuth error.
    AuthorizeError,
    /// Delivered, and the console did not try to redeem (nothing to redeem, or it
    /// cannot authenticate as this client).
    FrontChannelOnly,
    /// The code was redeemed.
    Exchanged,
    /// The redemption was attempted and failed.
    ExchangeFailed,
}

impl Outcome {
    pub const ALL: &'static [Outcome] = &[
        Self::StateUnknown,
        Self::AuthorizeError,
        Self::FrontChannelOnly,
        Self::Exchanged,
        Self::ExchangeFailed,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            Self::StateUnknown => "state_unknown",
            Self::AuthorizeError => "authorize_error",
            Self::FrontChannelOnly => "front_channel_only",
            Self::Exchanged => "exchanged",
            Self::ExchangeFailed => "exchange_failed",
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn decoded(claims: Value) -> DecodedToken {
        DecodedToken {
            header: json!({ "alg": "RS256" }),
            claims,
            signature: Ok(()),
        }
    }

    fn verdict(obs: &[Observation], check: Check) -> Verdict {
        obs.iter().find(|o| o.check == check).expect("checked").verdict
    }

    #[test]
    fn every_requirement_and_check_has_a_distinct_name() {
        let mut seen = std::collections::HashSet::new();
        for r in Requirement::ALL {
            assert!(seen.insert(r.as_str()), "two requirements are both {}", r.as_str());
            assert!(!r.title().is_empty());
        }
        let mut seen = std::collections::HashSet::new();
        for c in Check::ALL {
            assert!(seen.insert(c.as_str()), "two checks are both {}", c.as_str());
        }
        let mut seen = std::collections::HashSet::new();
        for o in Outcome::ALL {
            assert!(seen.insert(o.as_str()), "two outcomes are both {}", o.as_str());
        }
        let mut seen = std::collections::HashSet::new();
        for f in Fix::ALL {
            assert!(seen.insert(f.as_str()), "two places are both {}", f.as_str());
        }
    }

    #[test]
    fn a_nonce_that_does_not_match_is_a_failure_not_a_shrug() {
        let token = decoded(json!({ "nonce": "theirs", "iss": "i", "aud": "a", "exp": now() + 60 }));
        let expected = Expected {
            issuer: "i",
            audience: "a",
            nonce: Some("ours"),
            code: None,
            access_token: None,
        };
        let obs = check_id_token(&token, &expected);
        assert_eq!(verdict(&obs, Check::Nonce), Verdict::Fail);
        // And a matching one passes, so the test is about the comparison.
        let token = decoded(json!({ "nonce": "ours", "iss": "i", "aud": "a", "exp": now() + 60 }));
        assert_eq!(verdict(&check_id_token(&token, &expected), Check::Nonce), Verdict::Pass);
    }

    #[test]
    fn c_hash_and_at_hash_are_checked_against_the_values_in_the_response() {
        let code = "the-code";
        let access = "the.access.token";
        let token = decoded(json!({
            "nonce": "ours",
            "iss": "i",
            "aud": "a",
            "exp": now() + 60,
            "c_hash": half_hash(code),
            "at_hash": half_hash(access),
        }));
        let expected = Expected {
            issuer: "i",
            audience: "a",
            nonce: Some("ours"),
            code: Some(code),
            access_token: Some(access),
        };
        let obs = check_id_token(&token, &expected);
        assert_eq!(verdict(&obs, Check::CodeHash), Verdict::Pass);
        assert_eq!(verdict(&obs, Check::AccessTokenHash), Verdict::Pass);

        // The same token against a different code must fail, not pass quietly.
        let other = Expected {
            code: Some("another-code"),
            ..expected
        };
        assert_eq!(verdict(&check_id_token(&token, &other), Check::CodeHash), Verdict::Fail);
    }

    #[test]
    fn issuer_audience_and_expiry_are_compared_and_an_expired_token_fails() {
        let token = decoded(json!({ "iss": "wrong", "aud": ["x"], "exp": now() - 1, "nonce": "ours" }));
        let expected = Expected {
            issuer: "right",
            audience: "a",
            nonce: Some("ours"),
            code: None,
            access_token: None,
        };
        let obs = check_id_token(&token, &expected);
        assert_eq!(verdict(&obs, Check::Issuer), Verdict::Fail);
        assert_eq!(verdict(&obs, Check::Audience), Verdict::Fail);
        assert_eq!(verdict(&obs, Check::Expiry), Verdict::Fail);
    }

    #[test]
    fn an_array_audience_containing_the_client_matches() {
        let token = decoded(json!({ "iss": "i", "aud": ["other", "a"], "exp": now() + 60 }));
        let obs = check_access_token(&token, "i", Some("a"));
        assert_eq!(verdict(&obs, Check::Audience), Verdict::Pass);
    }

    #[test]
    fn a_bad_signature_is_reported_as_a_failed_check_rather_than_hidden() {
        let mut token = decoded(json!({ "iss": "i", "aud": "a", "exp": now() + 60 }));
        token.signature = Err("unknown kid".into());
        let obs = check_access_token(&token, "i", Some("a"));
        assert_eq!(verdict(&obs, Check::Signature), Verdict::Fail);
    }

    #[test]
    fn the_default_response_mode_keeps_tokens_out_of_a_query_string() {
        assert_eq!(Probe::default_mode(ResponseType::Code), ResponseMode::Query);
        for rt in [ResponseType::IdToken, ResponseType::Token, ResponseType::IdTokenToken] {
            assert_eq!(Probe::default_mode(rt), ResponseMode::FormPost, "{rt:?}");
        }
        assert_eq!(Probe::default_mode(ResponseType::CodeIdToken), ResponseMode::FormPost);
    }

    #[test]
    fn pkce_is_generated_for_every_response_type_that_carries_a_code() {
        for rt in ResponseType::ALL {
            let probe = Probe {
                response_type: *rt,
                ..Probe::default()
            };
            assert_eq!(probe.uses_pkce(), rt.has_code(), "{rt:?}");
        }
    }

    #[test]
    fn the_pkce_challenge_is_the_s256_one_the_token_endpoint_recomputes() {
        // The same construction `user_grants::authorization_code` checks against.
        use base64::Engine;
        use sha2::Digest;
        let verifier = "a-verifier-long-enough-to-be-accepted-by-the-server";
        let want = base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(sha2::Sha256::digest(verifier.as_bytes()));
        assert_eq!(pkce_challenge(verifier), want);
    }

    #[test]
    fn a_decoded_jwt_yields_its_header_and_claims() {
        use base64::Engine;
        let enc = |v: &Value| base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(serde_json::to_vec(v).unwrap());
        let token = format!(
            "{}.{}.signature",
            enc(&json!({ "alg": "RS256", "kid": "k" })),
            enc(&json!({ "sub": "u" }))
        );
        let (header, claims) = decode_parts(&token).unwrap();
        assert_eq!(header["kid"], "k");
        assert_eq!(claims["sub"], "u");
        assert!(decode_parts("not-a-jwt").is_err());
    }
}

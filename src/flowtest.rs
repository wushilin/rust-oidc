/// One thing a flow test needs. An enum rather than a list of strings so that a
/// requirement cannot be reported without a title and a place on the page.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Requirement {
    ServicePrincipal,
    Callback,
    Platform,
    ClientSecret,
    IdTokenToggle,
    AccessTokenToggle,
    OpenidScope,
    ResourceScope,
    Assignment,
    PasswordGrant,
    Delivery,
    Exchange,
}

impl Requirement {
    pub const ALL: &'static [Requirement] = &[
        Self::ServicePrincipal,
        Self::Callback,
        Self::Platform,
        Self::ClientSecret,
        Self::IdTokenToggle,
        Self::AccessTokenToggle,
        Self::OpenidScope,
        Self::ResourceScope,
        Self::Assignment,
        Self::PasswordGrant,
        Self::Delivery,
        Self::Exchange,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            Self::ServicePrincipal => "service_principal",
            Self::Callback => "callback",
            Self::Platform => "platform",
            Self::ClientSecret => "client_secret",
            Self::IdTokenToggle => "allow_id_token_implicit",
            Self::AccessTokenToggle => "allow_access_token_implicit",
            Self::OpenidScope => "openid_scope",
            Self::ResourceScope => "resource_scope",
            Self::Assignment => "app_role_assignment_required",
            Self::PasswordGrant => "allow_password_grant",
            Self::Delivery => "delivery",
            Self::Exchange => "token_exchange",
        }
    }

    /// What the row says it is about.
    pub fn title(self) -> &'static str {
        match self {
            Self::ServicePrincipal => "Service principal in this tenant",
            Self::Callback => "Flow-test callback registered",
            Self::Platform => "Platform of that callback",
            Self::ClientSecret => "Client secret",
            Self::IdTokenToggle => "ID tokens through the front channel",
            Self::AccessTokenToggle => "Access tokens through the front channel",
            Self::OpenidScope => "The openid scope",
            Self::ResourceScope => "The requested scope resolves",
            Self::Assignment => "User assignment",
            Self::PasswordGrant => "Password grant (ROPC)",
            Self::Delivery => "How the response gets back here",
            Self::Exchange => "Who redeems the code",
        }
    }
}

/// Whether a requirement is met. `Note` is neither: it is something the
/// administrator has to know and cannot fix, and it never blocks the flow.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Verdict {
    Pass,
    Fail,
    Note,
}

impl Verdict {
    pub const ALL: &'static [Verdict] = &[Self::Pass, Self::Fail, Self::Note];

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Pass => "pass",
            Self::Fail => "fail",
            Self::Note => "note",
        }
    }

    /// The word shown in the pill.
    pub fn label(self) -> &'static str {
        match self {
            Self::Pass => "ready",
            Self::Fail => "missing",
            Self::Note => "note",
        }
    }
}

/// Where the remedy for a finding is. This module names the place; the page builds
/// the link, because console URLs are not this module's business.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Fix {
    /// The application's own page in the console.
    ApplicationPage,
    /// The callback section further down the flow tester's own page.
    CallbackSection,
    /// One of the boxes in the form at the top of this page.
    ThisForm,
}

impl Fix {
    pub const ALL: &'static [Fix] = &[Self::ApplicationPage, Self::CallbackSection, Self::ThisForm];

    pub fn as_str(self) -> &'static str {
        match self {
            Self::ApplicationPage => "application_page",
            Self::CallbackSection => "callback_section",
            Self::ThisForm => "this_form",
        }
    }
}

/// One line of the readiness list: what is configured now, and what to do when it
/// is not what the chosen flow needs.
#[derive(Debug, Clone)]
pub struct Finding {
    pub requirement: Requirement,
    pub verdict: Verdict,
    /// What is configured, stated plainly.
    pub detail: String,
    /// What to change, and where. `None` when there is nothing to do.
    pub remedy: Option<String>,
    /// Where to go to do it, so the page can offer a link rather than only prose.
    pub fix: Option<Fix>,
}

impl Finding {
    fn new(requirement: Requirement, verdict: Verdict, detail: impl Into<String>) -> Self {
        Self {
            requirement,
            verdict,
            detail: detail.into(),
            remedy: None,
            fix: None,
        }
    }

    fn with_remedy(mut self, remedy: impl Into<String>) -> Self {
        self.remedy = Some(remedy.into());
        self
    }

    fn at(mut self, fix: Fix) -> Self {
        self.fix = Some(fix);
        self
    }
}

/// The answer to "why can I not test this yet".
#[derive(Debug, Clone)]
pub struct Readiness {
    pub findings: Vec<Finding>,
    /// Platform of the registered callback, when it is registered at all.
    pub platform: Option<RedirectPlatform>,
    /// Whether the console can complete the token exchange itself. False for a
    /// `web` client: it must authenticate, and only a hash of its secret is stored.
    pub can_exchange: bool,
}

impl Readiness {
    /// Nothing is missing. The start button appears only then.
    pub fn ready(&self) -> bool {
        !self.findings.iter().any(|f| f.verdict == Verdict::Fail)
    }

    pub fn missing(&self) -> usize {
        self.findings.iter().filter(|f| f.verdict == Verdict::Fail).count()
    }
}

/// Everything the readiness list needs to be computed from storage.
pub struct Subject<'a> {
    pub tenant: &'a Tenant,
    pub app: &'a Application,
    /// The signed-in administrator's own account id, when their account lives in
    /// this tenant. Used only to answer the assignment requirement for the most
    /// likely signing-in user; `None` means it is reported as uncheckable.
    pub admin_user_id: Option<&'a str>,
}

/// Work out, item by item, whether this application can run this flow.
///
/// Reads only. Every refusal the server would make is re-derived from the same
/// functions the server itself uses -- [`scopes::resolve`] for the scope,
/// [`apps::redirect_uris`] for the callback -- so the page cannot drift from the
/// endpoint it is describing.
pub async fn readiness(
    pool: &DbPool,
    url: &PublicUrl,
    subject: &Subject<'_>,
    probe: &Probe,
) -> anyhow::Result<Readiness> {
    let (tenant, app) = (subject.tenant, subject.app);
    let callback = callback_uri(url);
    let mut findings = Vec::new();

    // -- the service principal, which is what lets this tenant sign in to the app
    let sp = apps::service_principal(pool, &tenant.id, &app.app_id).await?;
    findings.push(match &sp {
        None => Finding::new(
            Requirement::ServicePrincipal,
            Verdict::Fail,
            format!("{} has no service principal in {}.", app.display_name, tenant.name),
        )
        .with_remedy("An application registered in another tenant needs a service principal here before anyone in this tenant can sign in to it."),
        Some(sp) if !sp.enabled => Finding::new(
            Requirement::ServicePrincipal,
            Verdict::Fail,
            "The service principal exists but is disabled, so every sign-in is refused.",
        )
        .with_remedy("Enable it before testing."),
        Some(_) => Finding::new(
            Requirement::ServicePrincipal,
            Verdict::Pass,
            format!("Enabled in {}.", tenant.name),
        ),
    });

    // -- the callback, and the platform it is registered under
    let registered = apps::redirect_uris(pool, app).await?;
    let platform = registered
        .iter()
        .find(|(_, uri)| apps::redirect_uri_matches(uri, &callback))
        .map(|(p, _)| *p);
    findings.push(match platform {
        Some(p) => Finding::new(
            Requirement::Callback,
            Verdict::Pass,
            format!("{callback} is registered under platform {}.", p.as_str()),
        ),
        None => Finding::new(
            Requirement::Callback,
            Verdict::Fail,
            format!("{callback} is not one of this application's redirect URIs, so the authorize request would be refused before it reached a sign-in page."),
        )
        .with_remedy(
            "Add it below, or on the application's own page. The console will not add it on its own: \
             a redirect URI is part of a registration, and a debug action must not change one silently.",
        )
        .at(Fix::CallbackSection),
    });
    findings.push(platform_finding(platform));

    // -- credentials. The console never has a secret value and never asks for one.
    //    A web client may authenticate with a certificate instead, so both count.
    let needs_credential = platform == Some(RedirectPlatform::Web) || probe.password_grant;
    let secret = apps::secrets(pool, app).await?.iter().any(|s| s.is_current(now()));
    let certificate = apps::key_credentials(pool, app)
        .await?
        .iter()
        .any(|c| c.is_current(now()));
    findings.push(match (needs_credential, secret, certificate) {
        (false, _, _) => Finding::new(
            Requirement::ClientSecret,
            Verdict::Note,
            "Not used by this flow: only a web client, and the password grant, authenticate at the token endpoint.",
        ),
        (true, false, false) => Finding::new(
            Requirement::ClientSecret,
            Verdict::Fail,
            "This client must authenticate at the token endpoint and has neither an unexpired client secret nor a current certificate credential.",
        )
        .with_remedy("Add a client secret on the application's page. You will never be asked to type one here.")
        .at(Fix::ApplicationPage),
        (true, s, c) => Finding::new(
            Requirement::ClientSecret,
            Verdict::Pass,
            format!(
                "{} registered and current. The value is not shown here and is not known to the console: only a SHA-256 hash of a secret is stored, and only the public part of a certificate.",
                match (s, c) {
                    (true, true) => "A client secret and a certificate credential are",
                    (true, false) => "A client secret is",
                    _ => "A certificate credential is",
                }
            ),
        ),
    });

    // -- the two front-channel toggles, named as the page that holds them names them
    findings.push(toggle_finding(
        Requirement::IdTokenToggle,
        probe.response_type.has_id_token(),
        app.allow_id_token_implicit,
        "id_token",
        "Allow implicit ID tokens",
    ));
    findings.push(toggle_finding(
        Requirement::AccessTokenToggle,
        probe.response_type.has_access_token(),
        app.allow_access_token_implicit,
        "token",
        "Allow implicit access tokens",
    ));

    // -- the scope, resolved by the same function the authorize endpoint uses
    let has_openid = probe.scope.split_whitespace().any(|s| s.eq_ignore_ascii_case("openid"));
    findings.push(match (probe.response_type.has_id_token(), has_openid) {
        (true, true) | (false, true) => Finding::new(
            Requirement::OpenidScope,
            Verdict::Pass,
            "Requested, so an ID token is issued.",
        ),
        (true, false) => Finding::new(
            Requirement::OpenidScope,
            Verdict::Fail,
            "The response type asks for an id_token, which requires the openid scope.",
        )
        .with_remedy("Add openid to the scope above.")
        .at(Fix::ThisForm),
        (false, false) => Finding::new(
            Requirement::OpenidScope,
            Verdict::Note,
            "Not requested. The flow will return an access token and no ID token.",
        ),
    });

    let grant = scopes::resolve(pool, tenant, &probe.scope).await;
    let resource_sp = match &grant {
        Ok(g) => {
            let detail = match &g.resource {
                Resource::Graph => format!(
                    "Resolves to the Microsoft Graph audience {}; scp will be {}.",
                    g.resource.audience(),
                    list(&g.scp)
                ),
                Resource::App { app, .. } => format!(
                    "Resolves to {} (audience {}); scp will be {}.",
                    app.display_name,
                    g.resource.audience(),
                    list(&g.scp)
                ),
            };
            findings.push(Finding::new(Requirement::ResourceScope, Verdict::Pass, detail));
            match &g.resource {
                Resource::App { sp, .. } => Some(sp.clone()),
                Resource::Graph => None,
            }
        }
        Err(err) => {
            findings.push(
                Finding::new(
                    Requirement::ResourceScope,
                    Verdict::Fail,
                    format!("AADSTS{}: {}", err.code.code(), err.message),
                )
                .with_remedy(
                    "A delegated permission has to be exposed and enabled on the API it names, \
                     and one request may target only one resource.",
                )
                .at(Fix::ThisForm),
            );
            None
        }
    };

    // -- assignment. Enforced on the *client's* service principal at sign-in; the
    //    resource's own requirement is reported because this server does not apply
    //    it, which is a difference worth seeing in a debugger.
    findings.push(assignment_finding(pool, subject, sp.as_ref(), resource_sp.as_ref()).await?);

    if probe.password_grant {
        findings.push(if app.allow_password_grant {
            Finding::new(
                Requirement::PasswordGrant,
                Verdict::Pass,
                "allow_password_grant is on, so the token endpoint accepts grant_type=password for this application.",
            )
            .with_remedy(
                "The console does not run this flow: it would have to send both the client secret, which it cannot read, \
                 and a user's password, which it will not collect. The request to run by hand is shown below.",
            )
        } else {
            Finding::new(
                Requirement::PasswordGrant,
                Verdict::Fail,
                "allow_password_grant is off, so grant_type=password is refused for this application.",
            )
            .with_remedy("Turn on \"Allow the resource owner password grant (ROPC)\" in the Grants section of the application's page.")
            .at(Fix::ApplicationPage)
        });
    }

    // -- how the response gets back, and who redeems the code
    findings.push(delivery_finding(probe));
    let can_exchange = matches!(
        platform,
        Some(RedirectPlatform::Spa) | Some(RedirectPlatform::PublicClient)
    );
    findings.push(exchange_finding(probe, platform, can_exchange));

    Ok(Readiness {
        findings,
        platform,
        can_exchange,
    })
}

fn list(values: &[String]) -> String {
    if values.is_empty() {
        "empty".to_string()
    } else {
        values.join(" ")
    }
}

fn platform_finding(platform: Option<RedirectPlatform>) -> Finding {
    match platform {
        None => Finding::new(
            Requirement::Platform,
            Verdict::Note,
            "Unknown until the callback is registered. The platform it is registered under decides the client rules.",
        ),
        Some(RedirectPlatform::Web) => Finding::new(
            Requirement::Platform,
            Verdict::Note,
            "web: a confidential client. It must authenticate at the token endpoint with its client secret or a certificate, and PKCE is optional.",
        ),
        Some(RedirectPlatform::Spa) => Finding::new(
            Requirement::Platform,
            Verdict::Note,
            "spa: PKCE is required, a secret must not be sent, and the token endpoint accepts the redemption only as a cross-origin request.",
        ),
        Some(RedirectPlatform::PublicClient) => Finding::new(
            Requirement::Platform,
            Verdict::Note,
            "publicClient: no secret, and no cross-origin requirement. PKCE is sent anyway, because a public client has nothing else binding the code to this request.",
        ),
    }
}

/// One of the two front-channel toggles. `needed` is whether the chosen response
/// type contains the value this toggle gates.
fn toggle_finding(
    requirement: Requirement,
    needed: bool,
    enabled: bool,
    response_value: &str,
    checkbox: &str,
) -> Finding {
    match (needed, enabled) {
        (false, _) => Finding::new(
            requirement,
            Verdict::Note,
            format!("Not required: this response type does not contain {response_value}."),
        ),
        (true, true) => Finding::new(requirement, Verdict::Pass, format!("On, so a response_type containing {response_value} is allowed.")),
        (true, false) => Finding::new(
            requirement,
            Verdict::Fail,
            format!("Off, so a response_type containing {response_value} is refused with AADSTS700054 before any sign-in page is shown."),
        )
        .with_remedy(format!("Tick \"{checkbox}\" in the Grants section of the application's page."))
        .at(Fix::ApplicationPage),
    }
}

async fn assignment_finding(
    pool: &DbPool,
    subject: &Subject<'_>,
    client_sp: Option<&apps::ServicePrincipal>,
    resource_sp: Option<&apps::ServicePrincipal>,
) -> anyhow::Result<Finding> {
    let client_requires = client_sp.is_some_and(|sp| sp.app_role_assignment_required);
    let resource_requires = resource_sp.is_some_and(|sp| sp.app_role_assignment_required);
    if !client_requires && !resource_requires {
        return Ok(Finding::new(
            Requirement::Assignment,
            Verdict::Note,
            "Neither this application nor the API it asks for requires an app role assignment, so any enabled user in this tenant can sign in.",
        ));
    }
    let resource_note = if resource_requires {
        " The API's own service principal also requires assignment; this server enforces that on the client's service principal only, so it will not refuse the token."
    } else {
        ""
    };
    if !client_requires {
        return Ok(Finding::new(
            Requirement::Assignment,
            Verdict::Note,
            format!("This application does not require an assignment.{resource_note}"),
        ));
    }
    let Some(admin_user_id) = subject.admin_user_id else {
        return Ok(Finding::new(
            Requirement::Assignment,
            Verdict::Note,
            format!(
                "This application requires an app role assignment, so whoever signs in must hold one directly or through a group. \
                 Your own account is not in this tenant, so the console cannot check it for you.{resource_note}"
            ),
        ));
    };
    let sp = client_sp.expect("client_requires implies a service principal");
    let assigned = apps::user_is_assigned(pool, &sp.id, admin_user_id).await?;
    Ok(if assigned {
        Finding::new(
            Requirement::Assignment,
            Verdict::Pass,
            format!("Required, and your own account holds one. Anybody else signing in needs one too.{resource_note}"),
        )
    } else {
        Finding::new(
            Requirement::Assignment,
            Verdict::Fail,
            format!("Required, and your own account does not hold one, so signing in as yourself would be refused with AADSTS50105.{resource_note}"),
        )
        .with_remedy("Assign a user or a group to an app role of this application, in the Role assignments section of its page.")
        .at(Fix::ApplicationPage)
    })
}

fn delivery_finding(probe: &Probe) -> Finding {
    match (probe.response_mode, probe.response_type.is_front_channel()) {
        (ResponseMode::Query, true) => Finding::new(
            Requirement::Delivery,
            Verdict::Fail,
            "response_mode=query cannot be used with a response type that carries a token; the server refuses it, and a token in a query string would end up in logs and Referer headers.",
        )
        .with_remedy("Choose form_post.")
        .at(Fix::ThisForm),
        (ResponseMode::Query, false) => Finding::new(
            Requirement::Delivery,
            Verdict::Pass,
            "The code comes back as a query string on a redirect to the console's callback.",
        ),
        (ResponseMode::FormPost, _) => Finding::new(
            Requirement::Delivery,
            Verdict::Pass,
            "The response is POSTed to the console's callback as a form body, which is how the console can read a token at all.",
        ),
        (ResponseMode::Fragment, _) => Finding::new(
            Requirement::Delivery,
            Verdict::Note,
            "A URL fragment never reaches the server, and the console's content security policy has no script to copy one into a form. \
             The flow will not be captured here: the console shows you the authorize URL to open yourself, and the response stays in your address bar.",
        )
        .with_remedy("Choose form_post to have the values arrive here instead.")
        .at(Fix::ThisForm),
    }
}

fn exchange_finding(probe: &Probe, platform: Option<RedirectPlatform>, can_exchange: bool) -> Finding {
    if !probe.response_type.has_code() {
        return Finding::new(
            Requirement::Exchange,
            Verdict::Note,
            "There is no code in this response, so there is nothing to redeem: everything the flow produces arrives in the front channel.",
        );
    }
    match (platform, can_exchange) {
        (_, true) => Finding::new(
            Requirement::Exchange,
            Verdict::Pass,
            "The console redeems the code itself, with a real HTTP request to this server's token endpoint, and shows you the request and the response.",
        ),
        (Some(RedirectPlatform::Web), _) => Finding::new(
            Requirement::Exchange,
            Verdict::Note,
            "A web client has to authenticate to redeem the code, and the console cannot: only a SHA-256 hash of the client secret is stored, by design. \
             The front channel is still tested end to end, and the exact token request is shown for you to run.",
        )
        .with_remedy(
            "To exercise the redemption too, use this tenant's flow tester client, which is registered as a public client and needs no secret.",
        )
        .at(Fix::CallbackSection),
        (None, _) => Finding::new(
            Requirement::Exchange,
            Verdict::Note,
            "Unknown until the callback is registered: the platform it is registered under decides whether the client has to authenticate.",
        ),
        (Some(_), false) => Finding::new(
            Requirement::Exchange,
            Verdict::Note,
            "The console cannot redeem the code for this client.",
        ),
    }
}


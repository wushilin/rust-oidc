/// The console's own callback, under the public URL's path prefix. One fixed URI:
/// it has to be registered on the application being tested, so it must not depend
/// on the tenant or on the application.
pub const CALLBACK_PATH: &str = "/admin/flow/callback";

/// The absolute URI that must be registered as a redirect URI.
pub fn callback_uri(url: &PublicUrl) -> String {
    format!("{}{CALLBACK_PATH}", url.base())
}

/// How long a sent-but-unanswered flow test stays pending.
///
/// Invented: ten minutes, the authorization code's own lifetime. The row only
/// exists to redeem a code, so keeping it past the point where the code itself
/// would be refused buys nothing.
pub const PENDING_LIFETIME_SECS: i64 = 600;

/// Display name of the client the console registers on request. Named for what it
/// is, so it is recognisable in the applications list without this table.
pub const TEST_CLIENT_NAME: &str = "Flow tester (admin console)";

/// `details.purpose` on the audit rows this feature writes through another
/// section's event, so "why does this application have that redirect URI" has an
/// answer in the log.
pub const PURPOSE: &str = "flow_test";

/// Form and query field names, spelled once.
pub const APP_FIELD: &str = "app";
pub const RESPONSE_TYPE_FIELD: &str = "response_type";
pub const RESPONSE_MODE_FIELD: &str = "response_mode";
pub const SCOPE_FIELD: &str = "scope";
pub const PROMPT_FIELD: &str = "prompt";
pub const PASSWORD_GRANT_FIELD: &str = "password_grant";
pub const PLATFORM_FIELD: &str = "platform";

/// The scope a fresh page offers. `openid profile email` is the smallest request
/// that produces an ID token worth reading.
pub const DEFAULT_SCOPE: &str = "openid profile email";

// ---- what is being tested ----

/// The configuration the administrator has chosen on the landing page. Everything
/// here comes from a closed set or is free text that only ever reaches a request.
#[derive(Debug, Clone)]
pub struct Probe {
    pub response_type: ResponseType,
    pub response_mode: ResponseMode,
    pub scope: String,
    pub prompt: Option<Prompt>,
    /// Whether the password grant is part of what is being tested, which turns on
    /// the `allow_password_grant` requirement.
    pub password_grant: bool,
}

impl Default for Probe {
    fn default() -> Self {
        Self {
            response_type: ResponseType::Code,
            response_mode: ResponseMode::Query,
            scope: DEFAULT_SCOPE.to_string(),
            prompt: None,
            password_grant: false,
        }
    }
}

impl Probe {
    /// The response mode this response type should use, which is what the page
    /// offers before the administrator changes it: `form_post` as soon as a token
    /// travels in the response, because the console has no script to read a
    /// fragment with and a query string must never carry a token.
    pub fn default_mode(response_type: ResponseType) -> ResponseMode {
        if response_type.is_front_channel() {
            ResponseMode::FormPost
        } else {
            ResponseMode::Query
        }
    }

    /// PKCE is sent whenever there is a code to protect. Generated by the server,
    /// never by a form.
    pub fn uses_pkce(&self) -> bool {
        self.response_type.has_code()
    }
}


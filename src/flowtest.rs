#[derive(sqlx::FromRow)]
struct PendingRow {
    tenant_id: String,
    client_app_id: String,
    response_type: String,
    response_mode: String,
    scope: String,
    redirect_uri: String,
    nonce: String,
    code_verifier: Option<String>,
    authorize_url: String,
}


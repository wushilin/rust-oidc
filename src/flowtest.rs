/// A flow test that has been sent and not yet answered.
#[derive(Debug, Clone)]
pub struct Pending {
    pub tenant_id: String,
    pub client_app_id: String,
    pub response_type: ResponseType,
    pub response_mode: ResponseMode,
    pub scope: String,
    pub redirect_uri: String,
    pub nonce: String,
    pub code_verifier: Option<String>,
    pub authorize_url: String,
}

/// What [`start`] produced: the `state` the browser carries, and the URL to send it to.
pub struct Started {
    pub state: String,
    pub authorize_url: String,
}

/// Build the authorize request, and remember what it has to come back with.
///
/// `admin_session` is the hash of the console session cookie, which is what binds
/// the pending row to the administrator who created it.
pub async fn start(
    pool: &DbPool,
    url: &PublicUrl,
    tenant: &Tenant,
    client_app_id: &str,
    probe: &Probe,
    admin_session: &str,
) -> anyhow::Result<Started> {
    let built = build_request(url, tenant, client_app_id, probe);
    let ts = now();
    // No scheduler in this process: clear what has expired while writing anyway,
    // the way `admin::session::create` does.
    sqlx::query(crate::db::q(pool, "DELETE FROM flow_tests WHERE expires_at < ?"))
        .bind(ts)
        .execute(pool)
        .await?;
    sqlx::query(crate::db::q(
        pool,
        "INSERT INTO flow_tests (state_hash, tenant_id, client_app_id, admin_session, response_type, response_mode,
                                 scope, redirect_uri, nonce, code_verifier, authorize_url, created_at, expires_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
    ))
    .bind(sha256_hex(built.state.as_bytes()))
    .bind(&tenant.id)
    .bind(client_app_id)
    .bind(admin_session)
    .bind(probe.response_type.as_str())
    .bind(probe.response_mode.as_str())
    .bind(&probe.scope)
    .bind(&built.redirect_uri)
    .bind(&built.nonce)
    .bind(built.code_verifier.as_deref())
    .bind(&built.authorize_url)
    .bind(ts)
    .bind(ts + PENDING_LIFETIME_SECS)
    .execute(pool)
    .await?;
    Ok(Started {
        state: built.state,
        authorize_url: built.authorize_url,
    })
}

/// The authorize request, before anything is stored. Separated so that the
/// fragment mode -- which is never captured, so never stored -- can be shown
/// without writing a row that would only expire.
pub struct BuiltRequest {
    pub state: String,
    pub nonce: String,
    pub code_verifier: Option<String>,
    pub redirect_uri: String,
    pub authorize_url: String,
}

pub fn build_request(url: &PublicUrl, tenant: &Tenant, client_app_id: &str, probe: &Probe) -> BuiltRequest {
    // 32 bytes each: `state` is the only thing standing between this callback and a
    // forged one, and the verifier has to be at least 43 characters.
    let state = b64url(&random_bytes(32));
    let nonce = b64url(&random_bytes(32));
    let code_verifier = probe.uses_pkce().then(|| b64url(&random_bytes(32)));
    let redirect_uri = callback_uri(url);

    let mut authorize = url::Url::parse(&url.tenant_url(&tenant.id, "oauth2/v2.0/authorize"))
        .expect("the public URL parses, so a path under it does");
    {
        let mut q = authorize.query_pairs_mut();
        q.append_pair("client_id", client_app_id);
        q.append_pair("response_type", probe.response_type.as_str());
        q.append_pair("response_mode", probe.response_mode.as_str());
        q.append_pair("redirect_uri", &redirect_uri);
        q.append_pair("scope", &probe.scope);
        q.append_pair("state", &state);
        // Always sent, even for a plain code flow: it is what lets the result page
        // check that the ID token belongs to this request.
        q.append_pair("nonce", &nonce);
        if let Some(verifier) = &code_verifier {
            q.append_pair("code_challenge", &pkce_challenge(verifier));
            q.append_pair("code_challenge_method", PKCE_METHOD);
        }
        if let Some(prompt) = probe.prompt {
            q.append_pair("prompt", prompt.as_str());
        }
    }
    BuiltRequest {
        state,
        nonce,
        code_verifier,
        redirect_uri,
        authorize_url: authorize.into(),
    }
}

/// The only code challenge method the tester uses. `plain` exists in the server
/// for compatibility; a debugger has no reason to send it.
pub const PKCE_METHOD: &str = "S256";

pub fn pkce_challenge(verifier: &str) -> String {
    use base64::Engine;
    use sha2::Digest;
    base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(sha2::Sha256::digest(verifier.as_bytes()))
}

/// Take the pending flow this `state` names, if it belongs to this console session
/// and has not expired. Single use: the row is deleted, and a second callback with
/// the same state finds nothing.
pub async fn take(pool: &DbPool, admin_session: &str, state: &str) -> anyhow::Result<Option<Pending>> {
    let hash = sha256_hex(state.as_bytes());
    let row: Option<PendingRow> = sqlx::query_as(crate::db::q(
        pool,
        "SELECT tenant_id, client_app_id, response_type, response_mode, scope, redirect_uri, nonce,
                code_verifier, authorize_url FROM flow_tests
         WHERE state_hash = ? AND admin_session = ? AND expires_at > ?",
    ))
    .bind(&hash)
    .bind(admin_session)
    .bind(now())
    .fetch_optional(pool)
    .await?;
    let Some(row) = row else { return Ok(None) };
    // Race-safe single use: only the request that removes the row may use it.
    let removed = sqlx::query(crate::db::q(
        pool,
        "DELETE FROM flow_tests WHERE state_hash = ? AND admin_session = ?",
    ))
    .bind(&hash)
    .bind(admin_session)
    .execute(pool)
    .await?
    .rows_affected();
    if removed != 1 {
        return Ok(None);
    }
    // A stored value this build cannot read is a refusal, not a default: the same
    // rule `stored_platform` follows for a grant.
    let response_type = ResponseType::parse(&row.response_type)
        .with_context(|| format!("pending flow test has an unknown response_type {:?}", row.response_type))?;
    let response_mode = ResponseMode::parse(&row.response_mode)
        .with_context(|| format!("pending flow test has an unknown response_mode {:?}", row.response_mode))?;
    Ok(Some(Pending {
        tenant_id: row.tenant_id,
        client_app_id: row.client_app_id,
        response_type,
        response_mode,
        scope: row.scope,
        redirect_uri: row.redirect_uri,
        nonce: row.nonce,
        code_verifier: row.code_verifier,
        authorize_url: row.authorize_url,
    }))
}


//! The console's flow tester: what a flow needs configured, the pending request it
//! holds between `/authorize` and its callback, and the checks it runs on what came
//! back.
//!
//! This module is the protocol half; [`crate::admin::flow`] is the HTML half. The
//! split is the same one the rest of the console keeps: a page may render a
//! [`Finding`], but it never decides what one is.
//!
//! Three properties are deliberate and are what make this safe to expose on a
//! console that is reachable from the internet:
//!
//! - **`state`, `nonce` and the PKCE verifier are generated here**, never taken
//!   from a form, and the row they live in is keyed by the *hash* of the state. A
//!   callback that cannot name a pending row is an error the page reports; it is
//!   also what stands in for a CSRF token on the callback, which an identity
//!   provider's `form_post` cannot carry.
//! - **The row is bound to the console session that created it** and deleted the
//!   moment it is used. Nothing that comes back -- no code, no token -- is ever
//!   written to the database or to the audit log.
//! - **The token exchange is a real HTTP request to our own token endpoint.** A
//!   debugger that bypassed the layer being debugged would eventually lie about it.

